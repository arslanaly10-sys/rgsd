import Image from "next/image";
import Link from "next/link";
import { notFound } from "next/navigation";
import QRCode from "qrcode";
import { PrintButton } from "@/components/print-button";
import { requireSession } from "@/lib/auth";
import { fmtDate } from "@/lib/format";
import { listWarranties } from "@/lib/quality";

/** Bilingual warranty certificate, issued once the client signs completion. */
export default async function WarrantyCertificate({ params }: { params: Promise<{ id: string }> }) {
  const s = await requireSession();
  const { id } = await params;
  if (!/^[0-9a-f-]{36}$/.test(id)) notFound();
  const w = (await listWarranties(s)).find((x) => x.id === id); // RLS: clients only their own
  if (!w || w.status !== "active") notFound();
  const qr = await QRCode.toString(`RGS warranty ${w.ref} · ${w.project_ref} · valid ${w.starts_on} to ${w.ends_on}`, { type: "svg", margin: 0 });
  return (
    <div className="min-h-dvh bg-canvas px-4 py-6 print:bg-white print:p-0">
      <div className="mx-auto mb-4 flex max-w-[860px] items-center justify-between print:hidden">
        <Link href={`${s.isStaff ? "/ops" : "/client"}/handover`} className="text-sm text-muted hover:text-ink">← Back</Link>
        <PrintButton label="Print / Save PDF" />
      </div>
      <article className="relative mx-auto max-w-[860px] overflow-hidden rounded-xl border-[6px] border-double border-ink/80 bg-white p-8 text-ink sm:p-12" dir="ltr">
        <div className="pointer-events-none absolute inset-0 flex items-center justify-center text-[110px] font-bold text-ink/[0.035] [transform:rotate(-24deg)]" aria-hidden>SAMPLE</div>
        <header className="flex items-start justify-between gap-6">
          <Image src="/brand/rgs-logo.png" alt="RGS" width={64} height={64} />
          <div className="text-center">
            <h1 className="font-display text-3xl font-semibold tracking-wide">Warranty Certificate</h1>
            <div className="mt-1 text-2xl font-semibold" dir="rtl">شهادة ضمان</div>
            <div className="mt-2 font-mono text-sm">{w.ref}</div>
          </div>
          <div className="size-20 [&_svg]:h-full [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: qr }} />
        </header>
        <section className="mt-8 grid gap-6 sm:grid-cols-2">
          <div className="grid gap-2 text-sm">
            <p>Resa Gulf Scaffolding Co. Ltd.{w.kind === "joint_manufacturer" ? ` and ${w.manufacturer}` : ""} warrant to <strong>{w.client}</strong> the following work:</p>
            <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1">
              <dt className="text-muted">Project</dt><dd>{w.project_ref} · {w.project_name}</dd>
              {w.area_code && <><dt className="text-muted">Area</dt><dd>{w.area_code}</dd></>}
              <dt className="text-muted">System</dt><dd>{w.system}</dd>
              <dt className="text-muted">Coverage</dt><dd>{w.coverage}</dd>
              <dt className="text-muted">Term</dt><dd><strong>{w.years} years</strong>: {fmtDate(w.starts_on, "en")} to {fmtDate(w.ends_on, "en")}</dd>
            </dl>
          </div>
          <div className="grid gap-2 text-sm" dir="rtl">
            <p>تضمن شركة ريسا الخليج للسقالات{w.kind === "joint_manufacturer" ? " بالاشتراك مع المصنع" : ""} لصالح <strong>{w.client_ar ?? w.client}</strong> الأعمال التالية:</p>
            <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1">
              <dt className="text-muted">المشروع</dt><dd>{w.project_ref}</dd>
              <dt className="text-muted">النظام</dt><dd>{w.system}</dd>
              <dt className="text-muted">التغطية</dt><dd>{w.coverage_ar ?? w.coverage}</dd>
              <dt className="text-muted">المدة</dt><dd><strong>{w.years} سنوات</strong>: من {fmtDate(w.starts_on, "ar")} إلى {fmtDate(w.ends_on, "ar")}</dd>
            </dl>
          </div>
        </section>
        {w.conditions && <p className="mt-6 rounded-lg bg-canvas p-3 text-xs"><strong>Conditions / الشروط:</strong> {w.conditions}</p>}
        <footer className="mt-10 grid grid-cols-2 gap-8 text-xs text-muted">
          <div className="border-t border-ink/40 pt-2">For Resa Gulf Scaffolding · لشركة ريسا الخليج</div>
          <div className="border-t border-ink/40 pt-2 text-end">{w.kind === "joint_manufacturer" ? `For ${w.manufacturer}` : "Quality Manager · مدير الجودة"}</div>
        </footer>
        <p className="mt-6 text-center text-[10px] text-muted">Demo certificate generated by RGS OneSite with SAMPLE data. Not a legal document.</p>
      </article>
    </div>
  );
}
